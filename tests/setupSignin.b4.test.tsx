describe('studio#1363: setup step 2 follows crew’s skills state', () => {
  it('reads each state from crew’s own block', () => {
    expect(skillsReading(skillsBlock('publishing', [PUBLISHING]))).toEqual({ stage: 'publishing', command: null, garden: null });
    expect(skillsReading(skillsBlock('fallback', [FALLBACK]))).toEqual({ stage: 'install', command: 'npx wicked-installer install wicked-garden', garden: 'missing' });
    expect(skillsReading(skillsBlock('config-error', [TOO_OLD]))).toEqual({ stage: 'install', command: 'npx wicked-installer install wicked-garden', garden: 'old' });
    expect(skillsReading(skillsBlock('published', [], { gen: 3, path: '/s/skills/snapshots/3' }))?.stage).toBe('published');
    expect(skillsReading(skillsBlock('blocked', [{ kind: 'skills.blocked', severity: 'error', message: 'x' }]))?.stage).toBe('todo');
    expect(skillsReading(null)).toBeNull();
    expect(skillsWords({ stage: 'publishing', command: null, garden: null })).not.toMatch(/^Not done/);
  });
  it.each([
    ['publishing', skillsBlock('publishing', [PUBLISHING]), 'Publishing now. Studio’s service publishes skills when it starts; this finishes on its own.', null],
    ['install', skillsBlock('fallback', [FALLBACK]), 'Not done. The skills package (wicked-garden) isn’t installed. Install it with this command', 'npx wicked-installer install wicked-garden'],
    ['install', skillsBlock('config-error', [TOO_OLD]), 'is older than studio needs. Update it with this command', 'npx wicked-installer install wicked-garden'],
  ])('step 2 reads %s in crew’s words', async (stage, skills, words, command) => {
    diagnostics = { ...diagnostics, skills };
    page('?setup=1');
    const step = await screen.findByTestId('agents-setup-step-skills');
    await waitFor(() => expect(step).toHaveAttribute('data-state', stage));
    expect(step).toHaveTextContent(words);
    expect(step).not.toHaveTextContent('Publish skills before starting work');
    expect(step).toHaveAttribute('data-done', 'false');
    if (command === null) expect(within(step).queryByTestId('agents-command')).toBeNull();
    else expect(within(step).getByTestId('agents-command')).toHaveTextContent(command);
  });
});

describe('crew#1527: the setup steps show the GitHub-or-local delivery choice before the first job', () => {
  it('reads crew’s readiness', () => {
    expect(deliveryStep(DELIVERY_READY, true)).toMatchObject({ done: true, state: 'ready', commands: [] });
    expect(deliveryStep(DELIVERY_SIGNED_OUT, true)).toMatchObject({ done: false, state: 'blocked', words: 'Not done. Sign in to GitHub for pull requests, or choose local delivery.', commands: ['gh auth login'] });
    expect(deliveryStep(DELIVERY_NO_GH, true).commands).toEqual([]);
    expect(deliveryStep(DELIVERY_NO_AUTHOR, true).commands).toEqual(['git config --global user.name "Your Name"', 'git config --global user.email you@example.com']);
    expect(deliveryStep(DELIVERY_UNKNOWN, true)).toMatchObject({ done: false, state: 'unknown' });
    expect(deliveryStep(undefined, true)).toMatchObject({ done: false, state: 'unknown', detail: null });
    // Local delivery asks GitHub for nothing.
    expect(deliveryStep(DELIVERY_SIGNED_OUT, false)).toMatchObject({ done: true, state: 'local' });
  });
  it('a signed-out GitHub reads as a choice, with the sign-in command and local delivery', async () => {
    known = { ...known, delivery: DELIVERY_SIGNED_OUT };
    page('?setup=1');
    const step = await screen.findByTestId('agents-setup-step-delivery');
    await waitFor(() => expect(step).toHaveAttribute('data-state', 'blocked'));
    expect(step).toHaveTextContent('Sign in to GitHub for pull requests, or choose local delivery.');
    expect(step).toHaveTextContent('gh is not signed in to github.com');
    expect(within(step).getByTestId('agents-command')).toHaveTextContent('gh auth login');
    fireEvent.click(within(step).getByTestId('agents-setup-delivery-local'));
    await waitFor(() => expect(step).toHaveAttribute('data-state', 'local'));
    expect(step).toHaveAttribute('data-done', 'true');
    expect(useComposerPrefsStore.getState().prefs.deliverPr).toBe(false);
  });
  it('a ready GitHub is done; an older service that sends no readiness is not checked, never done', async () => {
    known = { ...known, delivery: DELIVERY_READY };
    page('?setup=1');
    const step = await screen.findByTestId('agents-setup-step-delivery');
    await waitFor(() => expect(step).toHaveAttribute('data-done', 'true'));
    expect(step).toHaveTextContent('Done. Finished work opens a pull request on GitHub.');
    cleanup(); resetAgentsReads(); resetFirstUseReads(); clearCachedRoster();
    known = { git: null, languages: [], filesCounted: 0, nearby: [] };
    page('?setup=1');
    const older = await screen.findByTestId('agents-setup-step-delivery');
    await waitFor(() => expect(older).toHaveAttribute('data-state', 'unknown'));
    expect(older).toHaveTextContent('Not checked yet.');
    expect(older).toHaveAttribute('data-done', 'false');
  });
});

