describe('crew#1844: a cluster never set up reads its own reason and crew’s command', () => {
  it('is never "Kubernetes is stopped": its card names crew’s filled-in command with Copy', () => {
    const row = rowOf(noCluster());
    expect(helperRuntimeDown(row)).toBe(NO_CLUSTER);
    expect(runtimeStart(NO_CLUSTER)).toMatchObject({ title: 'Kubernetes isn’t set up for helpers yet', button: 'Set up Kubernetes', command: CORE });
    const copy = issueCopy({ code: 'signed_out', severity: 'problem', safety: false }, row, [row], Date.now(), true);
    expect(copy.title).toBe('Kubernetes isn’t set up for helpers yet');
    expect(copy.what).not.toMatch(/stopped/);
    expect(copy.fix[0]!.commands).toEqual([{ line: CORE, display: CORE, label: 'cluster setup' }]);
    // A stopped Kubernetes keeps its own words.
    expect(runtimeStart("Kubernetes isn't running")).toMatchObject({ what: 'Kubernetes is stopped', command: null });
  });
  it('the modal and setup step 4 show the command with Copy', async () => {
    roster = [noCluster()];
    page('?setup=1&fix=claude');
    const modal = await screen.findByTestId('agents-modal');
    expect(modal).toHaveTextContent('Kubernetes isn’t set up for helpers yet');
    expect(within(modal).getByTestId('agents-command')).toHaveTextContent(CORE);
    expect(within(modal).getByTestId('agents-copy')).toHaveAttribute('data-command-kind', 'cluster setup');
    const step = screen.getByTestId('agents-setup-step-runtime');
    await waitFor(() => expect(step).toHaveTextContent('Not done. Kubernetes isn’t set up for helpers yet.'));
    expect(step).not.toHaveTextContent('start it');
    expect(within(step).getByTestId('agents-command')).toHaveTextContent(CORE);
  });
  it('a refused sign-in’s cluster command is offered with Copy, never a placeholder', async () => {
    refusal = { status: 409, body: NO_CLUSTER_SIGNIN };
    page('?fix=claude');
    fireEvent.click(await screen.findByTestId('agents-signin'));
    const result = await screen.findByTestId('agents-check-result');
    await waitFor(() => expect(result).toHaveAttribute('data-state', 'signin-failed'));
    expect(within(result).getByTestId('agents-command')).toHaveTextContent(CORE);
    expect(result).not.toHaveTextContent(/<[^>]+>/);
  });
});

