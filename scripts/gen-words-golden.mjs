#!/usr/bin/env node
/**
 * Regenerates tests/fixtures/words-golden.json from crew's words layer (DES-CATALOG-002 §8.6 "One scorer"): the `/`
 * list's scorer (src/board/commandSearch.ts) must rank these words exactly as crew does. Run it after crew's
 * `workflow-catalog/detect.ts` or its catalog seeds change, then run tests/commandSearch.golden.test.ts.
 *
 *   node scripts/gen-words-golden.mjs <path to a wicked-crew checkout>
 */
import { build } from 'esbuild';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const crew = resolve(process.argv[2] ?? '../wicked-crew');
const src = join(crew, 'packages/crew/src/workflow-catalog');
const QUERIES = [
  'fix the crash when the login page loads',
  'upgrade our node service from 18 to 22',
  'move the billing api to another cloud',
  'add a dark mode toggle to the settings page',
  'write tests for the payment module',
  'plan tests for the checkout flow',
  'why did the deploy fail last night',
  'reconstruct what happened during the outage',
  'map the business domain of this repo',
  'check the docs still match the code',
  'build an mcp server for our tickets api',
  'make an editor plugin that shows a checklist',
  'security review of the auth service',
  'privacy audit of the user data flows',
  'make a slide deck about the release',
  'write a status update for the team',
  'record a demo video of the new dashboard',
  'draft epics from our requirements',
  'refactor the order service into smaller modules',
  'polish the error messages in the cli',
  'which flaky tests keep failing',
  'decide between postgres and sqlite for the cache',
  'risk analysis of the migration plan',
  'review recent work from this week',
  'propose rules from our past runs',
  'prepare the 2.0 release',
  'start a new cli tool for log parsing',
  'plan how to split the monolith',
  'map requirements to the code',
  'retro on the last sprint',
];
const dir = mkdtempSync(join(tmpdir(), 'words-golden-'));
try {
  const entry = join(dir, 'entry.ts');
  writeFileSync(entry, `
import { CATALOG_V2_CARDS, CATALOG_V2_CATEGORIES } from ${JSON.stringify(join(src, 'catalog-data-v2.ts'))};
import { detectable, wordsLayer, withoutAimed } from ${JSON.stringify(join(src, 'detect.ts'))};
const queries = ${JSON.stringify(QUERIES)};
const cards = CATALOG_V2_CARDS.filter(detectable).map((c) => ({
  id: c.id, category: c.category, title: c.title, words: c.words ?? [], outcome: c.outcome ?? '', needs: c.needs ?? [],
  variant: c.variant ? { options: c.variant.options.map((o) => ({ id: o.id, title: o.title, words: o.words ?? [] })) } : null,
}));
const cases = queries.map((q) => {
  if (withoutAimed(q) !== q) throw new Error('a golden query must carry no aimed text: ' + q);
  return { q, ranked: wordsLayer(q).ranked.map((r) => ({ card: r.card, score: r.score })) };
});
process.stdout.write(JSON.stringify({ categories: CATALOG_V2_CATEGORIES.map((c) => ({ id: c.id, title: c.title })), cards, cases }));
`);
  const out = join(dir, 'gen.mjs');
  await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error' });
  const json = JSON.parse(execFileSync(process.execPath, [out], { encoding: 'utf8' }));
  const crewHead = execFileSync('git', ['-C', crew, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
  const fixture = { $comment: `Generated by scripts/gen-words-golden.mjs from wicked-crew ${crewHead} (workflow-catalog/detect.ts wordsLayer). Do not edit by hand.`, ...json };
  writeFileSync(resolve('tests/fixtures/words-golden.json'), `${JSON.stringify(fixture, null, 2)}\n`);
  process.stdout.write(`wrote tests/fixtures/words-golden.json: ${json.cards.length} cards, ${json.cases.length} cases (crew ${crewHead})\n`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
