#!/usr/bin/env node
// Generates src/styles/themes/wicked-light.css and wicked-dark.css from the vendored wicked-design
// package (src/vendor/wicked-design/dist/tokens.json): the default themes are the design council's
// synthesis the operator picked on 2026-10-31. Never edit those two files by hand; change the package,
// re-vendor (wicked-web packages/design-system/scripts/vendor.mjs) and run `npm run gen:themes`.
//   node scripts/gen-wicked-themes.mjs          write the two theme files
//   node scripts/gen-wicked-themes.mjs --check  exit 1 when they are stale (tests/wickedThemes.generated.test.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(ROOT, 'src/vendor/wicked-design');

/** Studio-only colours the package does not define: one per agent, readable on each ground. */
const AGENTS = {
  light: '--agent-claude: #c2410c; --agent-codex: #2563eb; --agent-pi: #4d7c0f; --agent-copilot: #0f766e;\n  --agent-opencode: #a16207; --agent-agy: #be185d; --agent-gemini: #be185d; --agent-other: #64748b;',
  dark: '--agent-claude: #f0885a; --agent-codex: #6ea8fe; --agent-pi: #a3d65c; --agent-copilot: #3cc9bd;\n  --agent-opencode: #e3b341; --agent-agy: #f27aae; --agent-gemini: #f27aae; --agent-other: #94a3b8;',
};

/** A user-picked accent (Settings → Appearance, a learned brand) still drives the action colour:
 *  appearance.ts stamps data-accent="custom" when the primitives differ from the default preset.
 *  These are the wicked themes' accent formulas from before the synthesis, unchanged. */
const CUSTOM_ACCENT = {
  light: `  --accent:        hsl(var(--_accent-h) var(--_accent-s) var(--_accent-l));
  --accent-dim:    hsl(var(--_accent-h) var(--_accent-s) calc(var(--_accent-l) + 8%));
  --accent-subtle: hsl(var(--_accent-h) calc(var(--_accent-s) * 0.6) calc(var(--_accent-l) + 64%));
  --accent-hover:  hsl(var(--_accent-h) var(--_accent-s) calc(var(--_accent-l) - 6%));
  --accent-fg:     hsl(var(--_accent-h) 30% clamp(8%, calc((58% - var(--_accent-l)) * 100), 98%));
  --accent-wash:   color-mix(in oklab, var(--accent) 12%, transparent);`,
  dark: `  --accent:        hsl(var(--_accent-h) var(--_accent-s) calc(var(--_accent-l) + 40%));
  --accent-dim:    hsl(var(--_accent-h) var(--_accent-s) calc(var(--_accent-l) + 34%));
  --accent-subtle: hsl(var(--_accent-h) calc(var(--_accent-s) * 0.6) calc(var(--_accent-l) - 8%));
  --accent-hover:  hsl(var(--_accent-h) var(--_accent-s) calc(var(--_accent-l) + 46%));
  --accent-fg:     hsl(var(--_accent-h) 30% clamp(8%, calc((18% - var(--_accent-l)) * 100), 98%));
  --accent-wash:   color-mix(in oklab, var(--accent) 12%, transparent);`,
};

export function genThemeCss(tokens, vendored, theme) {
  const t = tokens.themes[theme];
  const s = tokens.scale;
  const sel = `[data-theme="wicked-${theme}"]`;
  const pkg = Object.entries(t).map(([n, v]) => `  --${n}: ${v};`).join('\n');
  return `/* GENERATED by scripts/gen-wicked-themes.mjs from src/vendor/wicked-design/dist/tokens.json
 * (${vendored.name} ${vendored.version}, wicked-web ${vendored.commit.slice(0, 7)}). Do not edit: change the package,
 * re-vendor it and run \`npm run gen:themes\`.
 *
 * wicked-${theme}: the default ${theme} theme, the design council's synthesis the operator picked on
 * 2026-10-31 (program design/DES-THEMES.md). Monochrome: neutral grounds, near-black / near-white ink and
 * actions, colour only for status. Studio's light.css rules (shadows, scrim, Nerve Center tones) apply to
 * wicked-light first; this block sets the family values on top. */

${sel} {
  color-scheme: ${theme};
  ${AGENTS[theme]}

  /* every wicked-design theme token, resolved (plugins read these names through the host) */
${pkg}

  /* studio's primitives and names, mapped onto the package */
  --_surface-0: ${t['surface-base']}; --_surface-1: ${t['surface-rail']}; --_surface-2: ${t['surface-card']};
  --_surface-3: ${t['surface-raised']}; --_surface-4: ${t['surface-overlay']};
  --_ink-faint: ${t['ink-dim']}; --_ink-soft: ${t['ink-muted']}; --_ink-strong: ${t['ink-body']}; --_ink-max: ${t['ink-high']};
  --accent-wash: ${t['accent-subtle']};          /* studio: selected / tinted fills = the synthesis' selected fill */
  --hover-wash: ${t['accent-wash']};             /* the synthesis' hover and current-item wash */
  --shadow-primary: ${t['shadow-button']}; --shadow-pressed: none;
  --focus-ring: 0 0 0 2px var(--focus-gap), 0 0 0 4px ${t.focus};
  --spark: ${t['accent-wicked']}; --spark-ink: ${t['accent-wicked-ink']};
  --nc-ok-bg: ${t['surface-card']}; --nc-ok-fg: ${t['ink-high']}; --nc-ok-edge: ${t.border};
  --nc-ok-hover: ${t['accent-subtle']}; --nc-ok-press: ${t['accent-subtle']};
  --font-sans: 'Inter', system-ui, -apple-system, 'Segoe UI', sans-serif;
  --text-md: ${s['text-body']};                 /* body copy */
  --radius-sm: ${s['radius-sm']}; --radius-md: ${s['radius-md']}; --radius-lg: ${s['radius-lg']}; --radius-xl: ${s['radius-xl']};
}

${sel}[data-accent="custom"] {
${CUSTOM_ACCENT[theme]}
}
`;
}

export function genAll() {
  const tokens = JSON.parse(readFileSync(join(VENDOR, 'dist/tokens.json'), 'utf8'));
  const vendored = JSON.parse(readFileSync(join(VENDOR, 'VENDORED.json'), 'utf8'));
  return Object.fromEntries(['light', 'dark'].map((th) => [join(ROOT, `src/styles/themes/wicked-${th}.css`), genThemeCss(tokens, vendored, th)]));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = genAll();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([p, c]) => readFileSync(p, 'utf8') !== c).map(([p]) => p);
    if (stale.length) { console.error(`stale: ${stale.join(', ')}; run npm run gen:themes`); process.exit(1); }
    console.log('wicked themes up to date');
  } else {
    for (const [p, c] of Object.entries(files)) writeFileSync(p, c);
    console.log(`wrote ${Object.keys(files).length} theme files`);
  }
}
