// testid-inventory.mjs — the shared scanner behind studio's data-testid contract (TH-13 / test-R13).
//
// `collectTestidInventory(rootDir)` scans src/ for data-testid DECLARATION sites (JSX
// attributes — selector *references* like `querySelector('[data-testid="x"]')` are skipped
// by the leading-`[` rule) and returns the inventory object that is committed at the repo
// root as `testid-inventory.json` and emitted into the built dist by vite.config.ts.
//
// Both consumers use this one function so they cannot disagree:
//   - scripts/generate-testid-inventory.mjs (npm run manifest:testids) writes the file;
//   - tests/testidInventory.test.ts re-scans live and fails CI on any drift vs the
//     committed file.
//
// Classification of an attribute value:
//   - "foo" / {'foo'} / a template with no ${}          → static  (exact string in the DOM)
//   - {`gate-approve-${runId}`}                          → dynamic (each ${expr} → '*')
//   - {cond ? A : B} with literal/undefined branches     → each branch classified on its own
//   - anything else (e.g. {a.testId})                    → computed (raw expression recorded)
//
// Determinism (the whole point of a lintable contract): files walked in sorted order,
// paths normalised to forward slashes, every list sorted by plain codepoint comparison
// (never localeCompare — locale-dependent), so the same tree yields byte-identical JSON
// on macOS, Linux, and Windows.

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** Bump when the JSON shape changes (consumers pin on this, not on studioVersion). */
export const INVENTORY_VERSION = 1;

/** File-header doc — the drift strategy, embedded in the committed artifact itself. */
export const INVENTORY_DOC = [
  'wicked-studio data-testid inventory — the UI selector contract, a versioned build artifact (TH-13 / test-R13).',
  'Generated by `npm run manifest:testids` (scripts/generate-testid-inventory.mjs) from src/ declaration sites.',
  'tests/testidInventory.test.ts re-scans src/ and fails CI on any drift vs this committed file, so a testid change only ships together with its reviewed inventory diff.',
  'The build also emits this file as dist/testid-inventory.json (vite.config.ts), so generators verify against the BUILT dist actually served — never source recon alone.',
  'Drift strategy: a selector miss in the deterministic executor FAILS the run — the model-free runner never decides what to click, so there is NO agentic fallback inside it. On failure the authoring agent re-authors the spec against the live DOM, the runner re-records deterministically, and the selector substitution lands in the spec diff for review.',
  "Entry kinds: `static` values appear verbatim in the DOM; `dynamic` are template-literal testids with each ${expr} normalised to '*'; `computed` carry the raw JSX expression — dynamic/computed resolve only against a live DOM.",
];

const SOURCE_EXT = /\.(ts|tsx|js|jsx)$/;

/** Recursively list source files under dir, repo-relative posix paths, sorted. */
function listSourceFiles(dir, prefix = '') {
  const out = [];
  const entries = readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const e of entries) {
    const rel = prefix === '' ? e.name : `${prefix}/${e.name}`;
    if (e.isDirectory()) out.push(...listSourceFiles(join(dir, e.name), rel));
    else if (e.isFile() && SOURCE_EXT.test(e.name)) out.push(rel);
  }
  return out;
}

/**
 * Given text and the index of an opening bracket ('{' or '('), return the index of its
 * matching closer, aware of nested braces/parens/brackets, string literals, and template
 * literals (including ${} expressions). Returns -1 if unbalanced.
 */
function matchBrace(text, start) {
  const stack = [];
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    const top = stack[stack.length - 1];
    if (top === "'" || top === '"') {
      if (c === '\\') i++;
      else if (c === top || c === '\n') stack.pop();
    } else if (top === '`') {
      if (c === '\\') i++;
      else if (c === '`') stack.pop();
      else if (c === '$' && text[i + 1] === '{') {
        stack.push('{');
        i++;
      }
    } else {
      if (c === "'" || c === '"' || c === '`') stack.push(c);
      else if (c === '{' || c === '(' || c === '[') stack.push(c);
      else if (c === '}' || c === ')' || c === ']') {
        stack.pop();
        if (stack.length === 0) return i;
      }
    }
  }
  return -1;
}

/** Minimal unescape for the string literals that appear in attribute values. */
function unquote(lit) {
  return lit.slice(1, -1).replace(/\\(.)/g, '$1');
}

/** Template literal (with backticks) → pattern with each ${expr} normalised to '*'. */
function templateToPattern(tpl) {
  let out = '';
  for (let i = 1; i < tpl.length - 1; i++) {
    const c = tpl[i];
    if (c === '\\') {
      out += tpl[i + 1];
      i++;
    } else if (c === '$' && tpl[i + 1] === '{') {
      const end = matchBrace(tpl, i + 1);
      if (end === -1) return null; // unbalanced — caller records as computed
      out += '*';
      i = end;
    } else {
      out += c;
    }
  }
  return out;
}

/**
 * Split a top-level ternary `cond ? then : else` (aware of nesting, strings, `?.`, `??`).
 * Returns { then, else } or null when the expression is not a top-level ternary.
 */
function splitTernary(expr) {
  const stack = [];
  let q = -1;
  let nested = 0;
  for (let i = 0; i < expr.length; i++) {
    const c = expr[i];
    const top = stack[stack.length - 1];
    if (top === "'" || top === '"') {
      if (c === '\\') i++;
      else if (c === top) stack.pop();
      continue;
    }
    if (top === '`') {
      if (c === '\\') i++;
      else if (c === '`') stack.pop();
      else if (c === '$' && expr[i + 1] === '{') {
        stack.push('{');
        i++;
      }
      continue;
    }
    if (c === "'" || c === '"' || c === '`') stack.push(c);
    else if (c === '{' || c === '(' || c === '[') stack.push(c);
    else if (c === '}' || c === ')' || c === ']') stack.pop();
    else if (stack.length === 0 && c === '?') {
      if (expr[i + 1] === '.' || expr[i + 1] === '?' || expr[i - 1] === '?') continue;
      if (q === -1) q = i;
      else nested++;
    } else if (stack.length === 0 && c === ':' && q !== -1) {
      if (nested > 0) nested--;
      else return { then: expr.slice(q + 1, i), else: expr.slice(i + 1) };
    }
  }
  return null;
}

/**
 * Classify one JSX expression (the inside of data-testid={...}) into inventory entries.
 * Returns an array of { kind: 'static'|'dynamic'|'computed', value } records.
 */
function classifyExpression(expr) {
  const t = expr.trim();
  if (t === '' || t === 'undefined' || t === 'null') return [];
  if (t.startsWith('(') && matchBrace(t, 0) === t.length - 1) {
    return classifyExpression(t.slice(1, -1));
  }
  if (/^'(?:[^'\\]|\\.)*'$/s.test(t) || /^"(?:[^"\\]|\\.)*"$/s.test(t)) {
    return [{ kind: 'static', value: unquote(t) }];
  }
  if (t.startsWith('`') && t.endsWith('`') && t.length >= 2) {
    const pattern = templateToPattern(t);
    if (pattern === null) return [{ kind: 'computed', value: collapse(t) }];
    return pattern.includes('*')
      ? [{ kind: 'dynamic', value: pattern }]
      : [{ kind: 'static', value: pattern }];
  }
  const ternary = splitTernary(t);
  if (ternary) {
    const branches = [...classifyExpression(ternary.then), ...classifyExpression(ternary.else)];
    // Only trust branch-wise classification when every branch resolved to a literal;
    // otherwise record the whole expression once, as computed.
    if (branches.length > 0 && branches.every((b) => b.kind !== 'computed')) return branches;
  }
  return [{ kind: 'computed', value: collapse(t) }];
}

function collapse(s) {
  return s.replace(/\s+/g, ' ').trim();
}

/** True when the match at `idx` is a selector/reference, not a JSX declaration. */
function isReference(text, idx) {
  for (let i = idx - 1; i >= 0; i--) {
    const c = text[i];
    if (c === ' ' || c === '\t') continue;
    return c === '[';
  }
  return false;
}

/**
 * From `start`, find the exclusive end of an object-property value expression:
 * the first top-level `,` or unmatched closer (`}`/`)`/`]`). String/template aware.
 */
function valueExpressionEnd(text, start) {
  const stack = [];
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    const top = stack[stack.length - 1];
    if (top === "'" || top === '"') {
      if (c === '\\') i++;
      else if (c === top || c === '\n') stack.pop();
      continue;
    }
    if (top === '`') {
      if (c === '\\') i++;
      else if (c === '`') stack.pop();
      else if (c === '$' && text[i + 1] === '{') {
        stack.push('{');
        i++;
      }
      continue;
    }
    if (c === "'" || c === '"' || c === '`') stack.push(c);
    else if (c === '{' || c === '(' || c === '[') stack.push(c);
    else if (c === '}' || c === ')' || c === ']') {
      if (stack.length === 0) return i;
      stack.pop();
    } else if (c === ',' && stack.length === 0) return i;
  }
  return text.length;
}

/**
 * Scan one file's text; returns { occurrences, entries: [{kind, value}] }.
 *
 * Two declaration forms are recognised:
 *   - JSX attribute:      data-testid="x"  /  data-testid={expr}
 *   - props-object key:   'data-testid': expr   (spread onto an element)
 * Selector *references* (`[data-testid="x"]` in querySelector strings/comments) are skipped.
 */
export function scanFileText(text) {
  const entries = [];
  let occurrences = 0;

  const attrRe = /data-testid\s*=\s*/g;
  let m;
  while ((m = attrRe.exec(text)) !== null) {
    if (isReference(text, m.index)) continue;
    const at = m.index + m[0].length;
    const c = text[at];
    if (c === '"' || c === "'") {
      const end = text.indexOf(c, at + 1);
      if (end === -1) continue;
      occurrences++;
      entries.push({ kind: 'static', value: text.slice(at + 1, end) });
      attrRe.lastIndex = end + 1;
    } else if (c === '{') {
      const end = matchBrace(text, at);
      if (end === -1) continue;
      occurrences++;
      entries.push(...classifyExpression(text.slice(at + 1, end)));
      attrRe.lastIndex = end + 1;
    }
  }

  const keyRe = /['"]data-testid['"]\s*:\s*/g;
  while ((m = keyRe.exec(text)) !== null) {
    const at = m.index + m[0].length;
    const end = valueExpressionEnd(text, at);
    occurrences++;
    entries.push(...classifyExpression(text.slice(at, end)));
    keyRe.lastIndex = end;
  }

  return { occurrences, entries };
}

/**
 * Build the full inventory for the repo at rootDir (must contain src/ and package.json).
 */
export function collectTestidInventory(rootDir) {
  const pkg = JSON.parse(readFileSync(join(rootDir, 'package.json'), 'utf8'));
  const srcDir = join(rootDir, 'src');
  const buckets = { static: new Map(), dynamic: new Map(), computed: new Map() };
  let occurrences = 0;
  const filesWithHits = new Set();

  for (const rel of listSourceFiles(srcDir)) {
    const text = readFileSync(join(srcDir, ...rel.split('/')), 'utf8');
    const { occurrences: n, entries } = scanFileText(text);
    if (n === 0) continue;
    occurrences += n;
    const file = `src/${rel}`;
    filesWithHits.add(file);
    for (const { kind, value } of entries) {
      const bucket = buckets[kind];
      if (!bucket.has(value)) bucket.set(value, new Set());
      bucket.get(value).add(file);
    }
  }

  const toRows = (map, key) =>
    [...map.entries()]
      .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
      .map(([value, files]) => ({
        [key]: value,
        files: [...files].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)),
      }));

  return {
    $doc: INVENTORY_DOC,
    version: INVENTORY_VERSION,
    studioVersion: pkg.version,
    counts: {
      files: filesWithHits.size,
      occurrences,
      static: buckets.static.size,
      dynamic: buckets.dynamic.size,
      computed: buckets.computed.size,
    },
    static: toRows(buckets.static, 'testId'),
    dynamic: toRows(buckets.dynamic, 'pattern'),
    computed: toRows(buckets.computed, 'expression'),
  };
}
